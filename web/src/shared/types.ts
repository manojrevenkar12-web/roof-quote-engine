  example: {
    id: string;
    partner: string;
    inputs: { voice: string; photos: string[]; plan: string | null; address: string };
    lines: ExampleLine[];
    llmTotal: number;
    llmEdits: number;
    proposedTotal: number;
    finalTotal: number;
    edits: number;
    sendable: boolean;
  };
